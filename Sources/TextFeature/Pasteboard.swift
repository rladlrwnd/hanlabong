import AppCore
import AppKit

/// 클립보드를 통째로(텍스트뿐 아니라 이미지·서식 등 모든 형식까지) 백업하고 되돌린다.
package struct PasteboardSnapshot {
    private let items: [[NSPasteboard.PasteboardType: Data]]

    package static func take(_ pasteboard: NSPasteboard = .general) -> PasteboardSnapshot {
        let items = (pasteboard.pasteboardItems ?? []).map { item in
            var copy: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { copy[type] = data }
            }
            return copy
        }
        return PasteboardSnapshot(items: items)
    }

    package func restore(to pasteboard: NSPasteboard = .general) {
        pasteboard.clearContents()
        guard !items.isEmpty else { return }
        let restored = items.map { saved -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in saved { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(restored)
    }
}

package extension NSPasteboard {
    /// 잠깐만 쓰고 지울 텍스트를 넣는다. 클립보드 관리 앱들이 기록에 남기지 않도록 표시를 붙인다.
    func writeTransient(_ text: String) {
        clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        writeObjects([item])
    }
}
